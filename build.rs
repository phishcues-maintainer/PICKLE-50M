fn is_post_unicode13(codepoint: u32) -> bool {
    POST_UNICODE13
        .binary_search_by(|&(start, end)| {
            if codepoint < start {
                std::cmp::Ordering::Greater
            } else if codepoint > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

fn class(character: char) -> u8 {
    if is_post_unicode13(character as u32) {
        return 0;
    }
    match get_general_category(character) {
        GeneralCategory::UppercaseLetter
        | GeneralCategory::LowercaseLetter
        | GeneralCategory::TitlecaseLetter
        | GeneralCategory::ModifierLetter
        | GeneralCategory::OtherLetter => 1,
        GeneralCategory::DecimalNumber
        | GeneralCategory::LetterNumber
        | GeneralCategory::OtherNumber => 2,
        GeneralCategory::NonspacingMark
        | GeneralCategory::SpacingMark
        | GeneralCategory::EnclosingMark => 3,
        GeneralCategory::Unassigned => 0,
        _ => 4,
    }
}

fn push_u24(output: &mut Vec<u8>, value: u32) {
    output.extend_from_slice(&[value as u8, (value >> 8) as u8, (value >> 16) as u8]);
}

fn main() {
    let mut ranges = Vec::new();
    let mut start = 0_u32;
    let mut previous = 0_u32;
    let mut current_class = 0_u8;
    for codepoint in 0..=0x10ffff_u32 {
        let next_class = char::from_u32(codepoint).map(class).unwrap_or(0);
        if next_class != current_class {
            if current_class != 0 {
                push_u24(&mut ranges, start);
                push_u24(&mut ranges, previous);
                ranges.push(current_class);
            }
            start = codepoint;
            current_class = next_class;
        }
        previous = codepoint;
    }
    if current_class != 0 {
        push_u24(&mut ranges, start);
        push_u24(&mut ranges, previous);
        ranges.push(current_class);
    }
    let output = PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("unicode13_categories.bin");
    fs::write(output, ranges).unwrap();
    println!("cargo:rerun-if-changed=build.rs");
}
